#!/usr/bin/env node

/**
 * 将 JSON Schema 同步为 Rust 与 TypeScript 类型。
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import console from "node:console";
import process from "node:process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const schemaRoot = resolve(root, "contracts/schema/v1");
const tsOut = resolve(root, "packages/contracts/src/generated");
const rsOut = resolve(root, "crates/common/src/contracts");
const dryRun = process.argv.includes("--dry-run");
const check = process.argv.includes("--check");
const tsTypes = { string: "string", boolean: "boolean", integer: "number", number: "number" };
const rsTypes = { string: "String", boolean: "bool", integer: "i64", number: "f64" };

function walk(directory, suffix) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? walk(path, suffix) : entry.name.endsWith(suffix) ? [path] : [];
    })
    .sort();
}

function names(path) {
  const parts = relative(schemaRoot, path).split(sep);
  const stem = parts.pop().replace(/\.schema\.json$/, "");
  const split = stem.includes(".") ? stem.split(".") : [stem];
  const segments = [...parts, ...split];
  const pascal = segments
    .flatMap((part) => part.split("_"))
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join("");
  return { pascal, snake: segments.join("_") };
}

function emitTs(name, schema) {
  const required = new Set(schema.required ?? []);
  const lines = [`export interface ${name} {`];
  for (const [property, spec] of Object.entries(schema.properties ?? {})) {
    lines.push(`  ${property}${required.has(property) ? "" : "?"}: ${tsTypes[spec.type] ?? "unknown"};`);
  }
  return `${lines.join("\n")}\n}\n`;
}

function emitRust(name, schema) {
  const required = new Set(schema.required ?? []);
  const lines = [
    "use serde::{Deserialize, Serialize};",
    "",
    "#[derive(Debug, Clone, Serialize, Deserialize)]",
    `pub struct ${name} {`,
  ];
  for (const [property, spec] of Object.entries(schema.properties ?? {})) {
    const base = rsTypes[spec.type] ?? "String";
    lines.push(`    pub ${property}: ${required.has(property) ? base : `Option<${base}>`},`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

const expected = new Map();
const tsExports = [];
const rsExports = [];
const schemas = walk(schemaRoot, ".schema.json");
for (const path of schemas) {
  const schema = JSON.parse(readFileSync(path, "utf8"));
  const { pascal, snake } = names(path);
  expected.set(resolve(tsOut, `${snake}.ts`), emitTs(pascal, schema));
  expected.set(resolve(rsOut, `${snake}.rs`), emitRust(pascal, schema));
  tsExports.push(`export type { ${pascal} } from "./${snake}";`);
  rsExports.push(`pub mod ${snake};`, `pub use ${snake}::${pascal};`);
}
expected.set(
  resolve(tsOut, "index.ts"),
  `// Auto-generated by sync-contracts.mjs — do not edit.\n\n${tsExports.join("\n")}\n`,
);
expected.set(
  resolve(rsOut, "mod.rs"),
  `// Auto-generated by sync-contracts.mjs — do not edit.\n\n${rsExports.join("\n")}\n`,
);

const generated = [
  ...walk(tsOut, ".ts"),
  ...walk(rsOut, ".rs"),
].map((path) => resolve(path));
const stale = generated.filter((path) => !expected.has(path));
const changed = [...expected].filter(([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content);

if (check) {
  if (stale.length || changed.length) {
    for (const path of stale) console.error(`stale: ${relative(root, path)}`);
    for (const [path] of changed) console.error(`outdated: ${relative(root, path)}`);
    process.exitCode = 1;
  } else {
    console.log(`contracts are synchronized (${schemas.length} schemas)`);
  }
} else if (dryRun) {
  for (const path of stale) console.log(`[delete] ${relative(root, path)}`);
  for (const [path] of changed) console.log(`[write] ${relative(root, path)}`);
} else {
  for (const path of stale) unlinkSync(path);
  for (const [path, content] of expected) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, "utf8");
  }
  console.log(`synchronized ${schemas.length} schemas`);
}
